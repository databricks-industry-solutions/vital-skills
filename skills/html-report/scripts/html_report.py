"""Build a self-contained scientific HTML report from a spec (no LaTeX, no network).

Usage (from a notebook):
    import sys; sys.path.insert(0, "<skills>/html-report/scripts")
    import html_report as hr

    spec = {
        "title": "TEDDY-70M on Databricks",
        "authors": "A. Researcher",
        "summary": "One paragraph, 150 words or fewer.",
        "sections": [
            {"title": "Results", "blocks": [
                {"p": "Text with **bold**, `code` and [links](https://arxiv.org/abs/2503.03485)."},
                {"figure": fig, "caption": "A full-sentence caption."},   # matplotlib Figure, PNG path or bytes
                {"table": df, "caption": "Table caption."},              # DataFrame or list of dicts
                {"checks": [{"check": "Fidelity", "threshold": "cosine >= 0.999",
                             "result": "min 0.999999", "passed": True}]},
                {"bullets": ["one", "two"]},
                {"path": "/Volumes/catalog/schema/volume/file.h5ad"},
            ]},
        ],
    }
    out = hr.build_report(spec, "/Volumes/<catalog>/<schema>/<volume>/report.html")
    print(out)                      # {path, bytes, sections, figures, tables, problems}

All text is HTML-escaped before the small inline markup (**bold**, `code`, [text](url)) is applied, so
notebook content cannot break the page. The file embeds every figure as a base64 PNG and loads nothing
from the network. A "Print / Save as PDF" button opens the browser's print dialog; it is hidden in print.
"""

