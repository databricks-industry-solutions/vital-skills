#!/usr/bin/env python3
"""Write CHECKS.md: every check the eval scores, per task, with its severity and what it guards.

Read from the sources the scorers use, so the list cannot drift from them:
expectations.json "checks" (severity and why, per task), corrected_checks.CORRECTIONS (which
replicated checks are judged by intent, and how) and practical_checks.CHECKS (the trial).

  python3 skills/open-weight-models/eval/list_checks.py           # print
  python3 skills/open-weight-models/eval/list_checks.py --write   # update CHECKS.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
if str(EVAL_DIR) not in sys.path:
    sys.path.insert(0, str(EVAL_DIR))

import corrected_checks  # noqa: E402 — same folder
import practical_checks  # noqa: E402
import scorers  # noqa: E402

OUT = EVAL_DIR / "CHECKS.md"

# Categories in report order: (key prefix after any "corrected/" / "new_checks/", title). The
# replicated Sep–Oct checks are named <category>/<check>; the new checks new_checks/<category>/<check>.
CATEGORIES = [
    ("download_staging", "Download and staging"),
    ("pyfunc_quality", "Model wrapper (PyFunc)"),
    ("model_registration", "Registration"),
    ("endpoint_deployment", "Endpoint deployment"),
    ("smoke_tests", "Tests before and after deploying"),
    ("forbidden_patterns", "Known-bad patterns"),
    ("edge_handling", "Edge cases"),
    ("ai_search", "Search (nearest-neighbour tasks)"),
    ("ai_gateway", "Governance: request logging"),
    ("uc_provenance", "Governance: registration and provenance"),
    ("existing_resources", "Safety: look before creating or deleting"),
    ("outcome", "Outcome: did what the run built work?"),
    ("convention", "Convention"),
]

COUNTED_AS = (
    "**Counted as:** *outcome* = measured on the live resources before teardown (`check_outcome.py`); "
    "*new* = read from the notebook code (`scorers.py`); *replicated* = a Sep–Oct 2026 sub-check, "
    "counted in its corrected form (`corrected_checks.py`) — *by intent* where the Sep–Oct logic matched "
    "literal text and now judges its goal, the original result kept as a ⚑ flag only; *convention* = "
    "reported, not counted."
)


def category(key: str) -> str:
    parts = key.split("/")
    return parts[1] if parts[0] == "new_checks" else parts[0]


def counted_as(key: str, corrected: dict) -> str:
    if key.startswith("outcome/"):
        return "outcome"
    if key.startswith("new_checks/"):
        return "new"
    if key.startswith("convention/"):
        return "convention"
    return "replicated, by intent" if key in corrected else "replicated"


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def corrected_rules() -> dict:
    """{expectations key: what the corrected check accepts} for the checks judged by intent."""
    return {scorers.mlflow_metric_name(k): meta["accepts"] for k, meta in corrected_checks.CORRECTIONS.items()}


def render() -> str:
    tasks = json.loads((EVAL_DIR / "expectations.json").read_text(encoding="utf-8"))
    corrected = corrected_rules()
    lines = [
        "# Checks the eval scores",
        "",
        "Generated by `list_checks.py` from `expectations.json`, `corrected_checks.py` and",
        "`practical_checks.py`; do not edit by hand. One section per model family, grouped by what the",
        "check is about; a check lists the tasks it applies to. Severity: **critical** = the endpoint does not work or gives wrong results;",
        "**major** = works but unsafe, ungoverned or not reproducible; **minor** = robustness or style.",
        "The severity tables in the reports count failed *counted* checks only.",
        "",
    ]
    families = {}
    for task in tasks:
        families.setdefault(task.get("model_family", "other"), []).append(task)
    for family, members in families.items():
        ids = [t["task_id"] for t in members]
        lines += [f"## {family} ({', '.join(ids)})", ""]
        rows = {}                       # key -> (meta, [task ids]); the first task's metadata
        for task in members:
            for key, meta in task["checks"].items():
                if "/" not in key:      # a phase placeholder that always passes where it does not apply
                    continue
                rows.setdefault(key, (meta, []))[1].append(task["task_id"])
        for task in members:            # metadata must agree across the family's tasks
            for key, (meta, _) in rows.items():
                other = task["checks"].get(key)
                if other is not None and (other.get("severity"), other.get("why")) != (meta.get("severity"), meta.get("why")):
                    raise ValueError(f"{family}: {key} differs between tasks; list it per task")
        unknown = [k for k in rows if category(k) not in dict(CATEGORIES)]
        if unknown:
            raise ValueError(f"{family}: no category for {unknown}; add it to CATEGORIES")
        lines += [COUNTED_AS, ""]
        for prefix, title in CATEGORIES:
            keys = [k for k in rows if category(k) == prefix]
            if not keys:
                continue
            lines += [f"### {title}", "", "| Check | Tasks | Severity | Counted as | What it guards |",
                      "|---|---|---|---|---|"]
            for key in keys:
                meta, applies = rows[key]
                why = _cell(meta.get("why", ""))
                if key in corrected:
                    why += f" *Judged by intent:* {_cell(corrected[key])}"
                on = "all" if len(applies) == len(ids) else ", ".join(applies)
                lines.append(f"| `{key}` | {on} | {meta.get('severity', '')} | {counted_as(key, corrected)} | {why} |")
            lines.append("")
    lines += [
        "## Practical checks — trial, not counted",
        "",
        "Goal-based checks that accept any valid way of reaching each goal (`practical_checks.py`);",
        "reported separately in each round, not used for the ship gate. `similarity_search_works`",
        "applies to search tasks only.",
        "",
        "| Check | Severity | Goal |",
        "|---|---|---|",
    ]
    for name, meta in practical_checks.CHECKS.items():
        lines.append(f"| `{name}` | {meta['severity']} | {_cell(meta['goal'])} |")
    for name, meta in practical_checks.GUIDELINES.items():
        lines.append(f"| `{name}` (guideline) | not counted | {_cell(meta['goal'])} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"write {OUT.name}")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(EVAL_DIR.parent.parent.parent)}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
